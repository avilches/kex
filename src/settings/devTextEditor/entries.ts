export const TEXT_KINDS = ["text", "title", "placeholder"] as const;
export type TextKind = (typeof TEXT_KINDS)[number];

export type TextEntry = {
  section: string;
  kind: TextKind;
  original: string;
  edited: string;
};

const MAX_LENGTH = 2000;

export function entryKey(kind: TextKind, original: string): string {
  return `${kind}\u0000${original}`;
}

export function isTextEntry(value: unknown): value is TextEntry {
  if (typeof value !== "object" || value === null) return false;
  const v = value as Record<string, unknown>;
  return (
    typeof v.section === "string" &&
    /^[a-z]+$/.test(v.section) &&
    (TEXT_KINDS as readonly unknown[]).includes(v.kind) &&
    typeof v.original === "string" &&
    v.original.length > 0 &&
    v.original.length <= MAX_LENGTH &&
    typeof v.edited === "string" &&
    v.edited.length > 0 &&
    v.edited.length <= MAX_LENGTH
  );
}

export function upsertEntry(entries: TextEntry[], entry: TextEntry): TextEntry[] {
  const key = entryKey(entry.kind, entry.original);
  const at = entries.findIndex((e) => entryKey(e.kind, e.original) === key);
  if (at < 0) return [...entries, entry];
  return entries.map((e, i) => (i === at ? entry : e));
}

export function removeEntry(
  entries: TextEntry[],
  kind: TextKind,
  original: string,
): TextEntry[] {
  const key = entryKey(kind, original);
  return entries.filter((e) => entryKey(e.kind, e.original) !== key);
}

const HEADER = `# Settings texts

Pending text edits made from the Settings window in dev mode (right-click a text, Edit). This file is generated by the dev server.

For each entry below, find the Original text in the source, replace it with the New text, and delete the entry from this file once applied. Values are JSON strings. A \`title\` entry is a tooltip and a \`placeholder\` entry is an input placeholder. The same Original may appear in several places: replace every occurrence that shows it in Settings.
`;

export function renderMarkdown(entries: TextEntry[]): string {
  if (entries.length === 0) return `${HEADER}\nNo pending edits.\n`;
  const blocks = entries.map(
    (e) =>
      `### ${e.section} (${e.kind})\n- Original: ${JSON.stringify(e.original)}\n- New: ${JSON.stringify(e.edited)}\n`,
  );
  return `${HEADER}\n${blocks.join("\n")}`;
}

function parseJson(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

export function parseMarkdown(markdown: string): TextEntry[] {
  const entries: TextEntry[] = [];
  const lines = markdown.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const heading = /^### ([a-z]+) \((text|title|placeholder)\)$/.exec(lines[i]);
    if (!heading) continue;
    const original = /^- Original: (.*)$/.exec(lines[i + 1] ?? "");
    const edited = /^- New: (.*)$/.exec(lines[i + 2] ?? "");
    if (!original || !edited) continue;
    const entry = {
      section: heading[1],
      kind: heading[2],
      original: parseJson(original[1]),
      edited: parseJson(edited[1]),
    };
    if (isTextEntry(entry)) entries.push(entry);
  }
  return entries;
}
